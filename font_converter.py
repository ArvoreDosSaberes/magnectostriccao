def convert_font_data(char_data_hex):
    """Converts a single character from row-major to column-major paged format."""
    # Create a 32x16 bit matrix
    bit_matrix = []
    for i in range(32):
        byte1 = char_data_hex[i * 2]
        byte2 = char_data_hex[i * 2 + 1]
        row_bits = f'{byte1:08b}{byte2:08b}'
        bit_matrix.append([int(b) for b in row_bits])

    # Transpose and create paged data
    output_bytes = []
    for page in range(4):
        for col in range(16):
            byte_val = 0
            for row_in_page in range(8):
                row = page * 8 + row_in_page
                # LSB corresponds to the top-most pixel in the page
                # To rotate +90 degrees (clockwise), the new (row, col) is (col, H-1-row)
                # Our input matrix is 32x16 (H=32, W=16). The output is column-major 16x32.
                # The output byte is for column `col` and `page`.
                # The original pixel we need to fetch is from bit_matrix[row_orig][col_orig]
                col_orig = row
                row_orig = (16 - 1) - col

                bit = bit_matrix[col_orig][row_orig]
                if bit == 1:
                    byte_val |= (1 << row_in_page)
            output_bytes.append(byte_val)
    return output_bytes

